"""
Local development database seeder.

Credentials are read from the environment (SEED_* variables, generated by
`scripts/generate_env.py`); nothing is hardcoded. Refuses to run in production.
@sad AD-09
@origin [Archetype Convention Addition]
"""

import sys
from datetime import UTC, datetime

from sqlalchemy.orm import Session

from app.config import settings
from app.modules.auth.infrastructure.models import UserModel
from app.modules.projects.infrastructure.models import ProjectMemberModel, ProjectModel
from app.modules.tasks.infrastructure.models import TaskModel
from app.shared.infrastructure.database import SessionLocal
from app.shared.infrastructure.hasher import Argon2PasswordHasher
from app.shared.infrastructure.id_generator import UuidGenerator


def _seed_user(
    db: Session,
    *,
    email: str,
    password: str,
    name: str,
    role: str,
    is_active: bool,
    now: datetime,
) -> str:
    existing = db.query(UserModel).filter_by(email=email).first()
    if existing is not None:
        return existing.id
    user_id = UuidGenerator().generate()
    db.add(
        UserModel(
            id=user_id,
            email=email,
            hashed_password=Argon2PasswordHasher().hash(password),
            name=name,
            role=role,
            is_active=is_active,
            created_at=now,
            updated_at=now,
        )
    )
    return user_id


def seed(db: Session | None = None) -> int:
    """Create the local demo users/project. Returns a process exit code."""
    if settings.APP_ENV == "production":
        print("Seeding is disabled when APP_ENV=production.")
        return 1

    plan = [
        (settings.SEED_ADMIN_EMAIL, settings.SEED_ADMIN_PASSWORD, "Administrador", "admin", True),
        (
            settings.SEED_MANAGER_EMAIL,
            settings.SEED_MANAGER_PASSWORD,
            "Gerente",
            "manager",
            True,
        ),
        (
            settings.SEED_DEVELOPER_EMAIL,
            settings.SEED_DEVELOPER_PASSWORD,
            "Desarrollador",
            "developer",
            True,
        ),
        (
            settings.SEED_DISABLED_EMAIL,
            settings.SEED_DISABLED_PASSWORD,
            "Cuenta Desactivada",
            "developer",
            False,
        ),
    ]
    if any(not email or password is None for email, password, *_ in plan):
        print("SEED_* variables are not configured. Run: python scripts/generate_env.py")
        return 1

    owns_session = db is None
    session = db or SessionLocal()
    now = datetime.now(UTC)
    try:
        ids: dict[str, str] = {}
        for email, password, name, role, is_active in plan:
            assert password is not None
            ids[role + str(is_active)] = _seed_user(
                session,
                email=str(email),
                password=password.get_secret_value(),
                name=name,
                role=role,
                is_active=is_active,
                now=now,
            )

        admin_id = ids["adminTrue"]
        if session.query(ProjectModel).filter_by(owner_id=admin_id).first() is None:
            id_gen = UuidGenerator()
            proj_id = id_gen.generate()
            manager_id = ids.get("managerTrue", admin_id)
            session.add(
                ProjectModel(
                    id=proj_id,
                    name="DashNode Initial Project",
                    description="Initial seed project for DashNode platform",
                    owner_id=admin_id,
                    manager_id=manager_id,
                    priority="media",
                    tech_stack="[]",
                    meeting_link=None,
                    status="planificacion",
                    created_at=now,
                    updated_at=now,
                )
            )
            session.flush()
            session.add(
                ProjectMemberModel(project_id=proj_id, user_id=admin_id, role="lead", joined_at=now)
            )
            session.add(
                TaskModel(
                    id=id_gen.generate(),
                    project_id=proj_id,
                    title="Setup development environment",
                    description="Run docker-compose and verify backend",
                    status="todo",
                    priority="high",
                    assignee_id=admin_id,
                    creator_id=admin_id,
                    has_open_fix=False,
                    created_at=now,
                    updated_at=now,
                )
            )
        session.commit()
        print("Seed data is ready.")
        return 0
    except Exception as error:
        session.rollback()
        print(f"Error seeding database: {type(error).__name__}")
        return 1
    finally:
        if owns_session:
            session.close()


if __name__ == "__main__":
    sys.exit(seed())
